/// Per-core-service identification badges init stamps on the
/// `ROLE_INIT_CONTROL` send cap it delivers to each core service. Those
/// servers send *to* init through that cap; init's reactor and fault
/// dispatcher authenticate inbound messages by the badge so each sender is
/// uniquely identified — only mmsrv may issue `INIT_REPORT_FAULT`, and each
/// `INIT_CORE_READY` is matched to the exact server init just spawned. This is
/// the server→init direction, unrelated to the per-client control caps that
/// authorize the init→server admin surface.
pub const INIT_BADGE_FROM_MMSRV: u64 = 0xF000_0000_0000_0002;
pub const INIT_BADGE_FROM_NAMESRV: u64 = 0xF000_0000_0000_0004;
pub const INIT_BADGE_FROM_RSRCSRV: u64 = 0xF000_0000_0000_0005;
