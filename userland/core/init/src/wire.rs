// The `GET_PROC_INFO` sub-op family is canonically defined in
// `trona_protocol::init` — its doc comments specify the exact reply
// layouts VFS decodes (PROC_INFO_FULL regs[1..11], EXE_PATH=0x0A, the
// extended CPU_INFO / CLIENT_VM_STATS / PROC_INFO_FULL ops).
// `posix.rs` carries a stale lower-numbered copy (EXE_PATH=0x07,
// DUMP_PENDING=0x08); the init server must use the `init.rs` values so
// VFS↔init sub-op numbers match. Only `GET_PROC_INFO` (0x00) and
// `LIST_PIDS` (0x01) are posix-only and stay imported above.
