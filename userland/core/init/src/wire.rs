// Cookie kinds for init's `EventLoop`. Encoded into the
// upper byte of the kernel cookie via
// [`trona_server::event_loop::encode_cookie`]; `live_gen` is
// supplied by `state.cookie_table.arm` so stale fires after teardown
// drop on dispatch.
//
// `INIT_COOKIE_KIND_REQUEST_MP` carries the per-client request MP
// recv side. The target keeps its semantic payload (`client_id`)
// inside the dispatcher's `CookieTable<InitTarget>` entry, not in
// the cookie itself — the cookie's `slot` field is opaque to callers.

pub const INIT_COOKIE_KIND_REQUEST_MP: u8 = 0x01;
pub const INIT_COOKIE_KIND_MASTER_MP: u8 = 0x02;
pub const INIT_COOKIE_KIND_WORKER_COMPLETION: u8 = 0x03;
pub const INIT_COOKIE_KIND_CONTROL_TIMER: u8 = 0x05;
pub const INIT_COOKIE_KIND_NAMESRV_REGISTER_EVENT: u8 = 0x06;

