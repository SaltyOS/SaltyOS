/// Print a number
fn print_number(mut n: u32) {
    if n == 0 {
        print_char(b'0');
        return;
    }

    let mut buffer = [0u8; 10];
    let mut i = 0;

    while n > 0 {
        buffer[i] = b'0' + (n % 10) as u8;
        n /= 10;
        i += 1;
    }

    while i > 0 {
        print_char(buffer[i - 1]);
        i -= 1;
    }
}

/// Scroll the screen up one line
fn scroll() {
    unsafe {
        if FB_ENABLED {
            fb_clear(0, 0, 0);
            CURSOR_X = 0;
            CURSOR_Y = 0;
            return;
        }

        let vga_buffer = VGA_BUFFER as *mut u16;

        for i in 0..(VGA_WIDTH * (VGA_HEIGHT - 1)) {
            let val = core::ptr::read_volatile(vga_buffer.add(i + VGA_WIDTH));
            core::ptr::write_volatile(vga_buffer.add(i), val);
        }

        for i in (VGA_WIDTH * (VGA_HEIGHT - 1))..(VGA_WIDTH * VGA_HEIGHT) {
            core::ptr::write_volatile(vga_buffer.add(i), 0x0f20);
        }

        CURSOR_X = 0;
        CURSOR_Y = VGA_HEIGHT - 1;
    }
}

/// Halt the CPU
fn halt() -> ! {
    loop {
        unsafe {
            core::arch::asm!("hlt", options(nomem, nostack));
        }
    }
}

/// Panic handler
#[panic_handler]
fn panic(info: &PanicInfo) -> ! {
    print_string("\r\n*** KERNEL PANIC ***\r\n");
    let _ = print_panic_info(info);
    halt()
}

/// Exception handling personality for no_std
#[unsafe(no_mangle)]
pub extern "C" fn rust_eh_personality() -> ! {
    loop {
        unsafe { core::arch::asm!("hlt") };
    }
}

/// Print panic info
fn print_panic_info(info: &PanicInfo) -> Result<(), core::fmt::Error> {
    use core::fmt::Write;

    struct Writer;
    impl Write for Writer {
        fn write_str(&mut self, s: &str) -> Result<(), core::fmt::Error> {
            print_string(s);
            Ok(())
        }
    }

    let mut writer = Writer;
    write!(&mut writer, "{}", info)
}

/// Memory compare (for compiler builtins)
#[unsafe(no_mangle)]
unsafe extern "C" fn memcmp(s1: *const u8, s2: *const u8, n: usize) -> i32 {
    for i in 0..n {
        unsafe {
            let a = core::ptr::read(s1.add(i));
            let b = core::ptr::read(s2.add(i));
            if a != b {
                return (a as i32) - (b as i32);
            }
        }
    }
    0
}
