//! SaltyOS Kernel
//!
//! This kernel:
//! 1. Parses SKA BootInfo
//! 2. Initializes architecture (GDT, IDT, interrupts)
//! 3. Prints "Hello, SaltyOS!"
//! 4. Halts

#![no_std]
#![no_main]

use core::panic::PanicInfo;
use saltyos_ska::{BootInfo, BootFlags, FramebufferInfo, PixelFormat, BOOTINFO_MAGIC, BOOTINFO_VERSION};

// Architecture and syscall modules
mod arch;
mod ssabi;
mod mm;
mod boot;

/// VGA buffer address
const VGA_BUFFER: usize = 0xb8000;

/// VGA width
const VGA_WIDTH: usize = 80;

/// VGA height
const VGA_HEIGHT: usize = 25;

/// Global cursor position
static mut CURSOR_X: usize = 0;
static mut CURSOR_Y: usize = 0;
static mut FB_ENABLED: bool = false;
static mut FB_INFO: FramebufferInfo = FramebufferInfo {
    address: saltyos_ska::PhysAddr(0),
    width: 0,
    height: 0,
    pitch: 0,
    format: PixelFormat::Rgb,
    bpp: 0,
};
const COM1_PORT: u16 = 0x3f8;

/// Kernel entry point called from boot.S
#[unsafe(no_mangle)]
pub unsafe extern "sysv64" fn kernel_main(bootinfo: &BootInfo) -> ! {
    serial_init();

    if bootinfo.flags.contains(BootFlags::FRAMEBUFFER) {
        if let Some(info) = bootinfo.framebuffer {
            FB_INFO = info;
            FB_ENABLED = true;
        }
    }
    // Clear screen
    clear_screen();

    // Validate BootInfo
    if bootinfo.magic != *BOOTINFO_MAGIC {
        print_string("Error: Invalid BootInfo magic!\r\n");
        halt();
    }

    if bootinfo.version != BOOTINFO_VERSION {
        print_string("Error: Unsupported BootInfo version!\r\n");
        halt();
    }
    if bootinfo.size != 0 && (bootinfo.size as usize) < core::mem::size_of::<BootInfo>() {
        print_string("Error: BootInfo size too small!\r\n");
        halt();
    }

    print_string("arch::init() start\r\n");
    // NEW: Initialize architecture (GDT, IDT, interrupts, syscall)
    arch::init();
    print_string("arch::init() done\r\n");

    print_string("mm::init() start\r\n");
    unsafe { mm::init(bootinfo); }
    print_string("mm::init() done\r\n");
    arch::enable_interrupts();

    // Print banner
    print_string("SaltyOS vNext\r\n");
    print_string("========================\r\n");
    print_string("\r\n");

    // Print boot source
    let boot_source = if bootinfo.flags.contains(BootFlags::UEFI) {
        "UEFI"
    } else if bootinfo.flags.contains(BootFlags::BIOS) {
        "BIOS"
    } else {
        "Unknown"
    };

    print_string("Booted via: ");
    print_string(boot_source);
    print_string("\r\n");
    print_string("Memory map entries: ");
    print_number(bootinfo.memory_map_entries);
    print_string("\r\n");

    // Test syscall using inline assembly (if we wanted to test from kernel)
    // For now, we'll skip this test since we're in kernel mode
    print_string("\r\n");
    print_string("Hello, SaltyOS!\r\n");
    print_string("\r\n");
    if bootinfo.flags.contains(BootFlags::INITRD) {
        if let Some(initrd) = bootinfo.initrd {
            print_string("Initrd addr: ");
            print_hex(initrd.address.as_u64());
            print_string(" size: ");
            print_hex(initrd.size);
            print_string("\r\n");
            match boot::initrd::find_init(initrd.address, initrd.size) {
                Ok(Some(init_data)) => {
                    match boot::user::load_and_enter(init_data) {
                        Ok((entry, stack_top)) => unsafe {
                            print_string("Entering user mode...\r\n");
                            print_string("user entry: ");
                            print_hex(entry);
                            print_string("\r\n");
                            print_string("user stack: ");
                            print_hex(stack_top);
                            print_string("\r\n");
                            arch::enter_user_mode(entry, stack_top);
                        },
                        Err(err) => {
                            print_string("Error: Failed to load /init from initrd: ");
                            print_string(err);
                            print_string("\r\n");
                            halt();
                        }
                    }
                }
                Ok(None) => {
                    print_string("Error: /init not found in initrd.\r\n");
                    halt();
                }
                Err(err) => {
                    print_string("Error: initrd parse failed: ");
                    print_string(err);
                    print_string("\r\n");
                    halt();
                }
            }
        } else {
            print_string("Error: INITRD flag set but no module.\r\n");
            halt();
        }
    }

    print_string("Entering user mode...\r\n");

    unsafe {
        let entry = arch::user_test_entry_low();
        let user_stack = arch::user_stack_top();
        let kv = arch::kernel_virt_base();
        let kp = arch::kernel_phys_base();
        print_string("kernel virt base: ");
        print_hex(kv);
        print_string("\r\n");
        print_string("kernel phys base: ");
        print_hex(kp);
        print_string("\r\n");
        print_string("user entry: ");
        print_hex(entry);
        print_string("\r\n");
        print_string("user stack: ");
        print_hex(user_stack);
        print_string("\r\n");
        arch::enter_user_mode(entry, user_stack);
    }
}

/// Clear the VGA screen
fn clear_screen() {
    unsafe {
        if FB_ENABLED {
            fb_clear(0, 0, 0);
            CURSOR_X = 0;
            CURSOR_Y = 0;
            return;
        }

        let vga_buffer = VGA_BUFFER as *mut u16;

        for i in 0..VGA_WIDTH * VGA_HEIGHT {
            core::ptr::write_volatile(vga_buffer.add(i), 0x0f20);
        }

        CURSOR_X = 0;
        CURSOR_Y = 0;
    }
}

/// Print a string to VGA
pub(crate) fn print_string(s: &str) {
    for byte in s.bytes() {
        print_char(byte);
    }
}

/// Print a single character to VGA
pub(crate) fn print_char(c: u8) {
    unsafe {
        serial_write(c);
        if FB_ENABLED {
            fb_print_char(c);
            return;
        }

        let vga_buffer = VGA_BUFFER as *mut u16;

        match c {
            b'\r' => {
                CURSOR_X = 0;
            }
            b'\n' => {
                CURSOR_X = 0;
                CURSOR_Y += 1;
            }
            0x20..=0x7e => {
                let attr: u16 = 0x0f;
                let idx = CURSOR_Y * VGA_WIDTH + CURSOR_X;
                core::ptr::write_volatile(vga_buffer.add(idx), (c as u16) | (attr << 8));
                CURSOR_X += 1;
            }
            _ => {
                let attr: u16 = 0x0f;
                let idx = CURSOR_Y * VGA_WIDTH + CURSOR_X;
                core::ptr::write_volatile(vga_buffer.add(idx), (b'?' as u16) | (attr << 8));
                CURSOR_X += 1;
            }
        }

        if CURSOR_X >= VGA_WIDTH {
            CURSOR_X = 0;
            CURSOR_Y += 1;
        }

        if CURSOR_Y >= VGA_HEIGHT {
            scroll();
        }
    }
}

fn serial_init() {
    unsafe {
        outb(COM1_PORT + 1, 0x00);
        outb(COM1_PORT + 3, 0x80);
        outb(COM1_PORT + 0, 0x01);
        outb(COM1_PORT + 1, 0x00);
        outb(COM1_PORT + 3, 0x03);
        outb(COM1_PORT + 2, 0xC7);
        outb(COM1_PORT + 4, 0x0B);
    }
}

fn serial_write(byte: u8) {
    unsafe {
        while (inb(COM1_PORT + 5) & 0x20) == 0 {}
        outb(COM1_PORT, byte);
    }
}

fn print_hex(mut n: u64) {
    print_string("0x");

    let mut buffer = [0u8; 16];
    let mut i = 0;

    if n == 0 {
        print_char(b'0');
        return;
    }

    while n > 0 {
        let digit = (n & 0xf) as u8;
        buffer[i] = if digit < 10 { b'0' + digit } else { b'a' + digit - 10 };
        n >>= 4;
        i += 1;
    }

    while i > 0 {
        print_char(buffer[i - 1]);
        i -= 1;
    }
}

unsafe fn outb(port: u16, val: u8) {
    core::arch::asm!("out dx, al", in("dx") port, in("al") val, options(nomem, nostack));
}

unsafe fn inb(port: u16) -> u8 {
    let mut val: u8;
    core::arch::asm!("in al, dx", in("dx") port, out("al") val, options(nomem, nostack));
    val
}

// Minimal C runtime shims to avoid compiler-emitted SSE mem* in early boot.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn memcpy(dst: *mut u8, src: *const u8, n: usize) -> *mut u8 {
    core::arch::asm!(
        "rep movsb",
        inout("rdi") dst => _,
        inout("rsi") src => _,
        inout("rcx") n => _,
        options(nostack, preserves_flags)
    );
    dst
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn memmove(dst: *mut u8, src: *const u8, n: usize) -> *mut u8 {
    if (dst as usize) < (src as usize) {
        core::arch::asm!(
            "rep movsb",
            inout("rdi") dst => _,
            inout("rsi") src => _,
            inout("rcx") n => _,
            options(nostack, preserves_flags)
        );
    } else if n != 0 {
        let dst_end = dst.add(n - 1);
        let src_end = src.add(n - 1);
        core::arch::asm!(
            "std",
            "rep movsb",
            "cld",
            inout("rdi") dst_end => _,
            inout("rsi") src_end => _,
            inout("rcx") n => _,
            options(nostack, preserves_flags)
        );
    }
    dst
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn memset(dst: *mut u8, value: i32, n: usize) -> *mut u8 {
    let addr = dst as u64;
    let sign = (addr >> 47) & 1;
    let upper = addr >> 48;
    let canonical = (sign == 0 && upper == 0) || (sign == 1 && upper == 0xffff);
    if !canonical {
        let mut ret: u64 = 0;
        core::arch::asm!("mov {}, [rsp]", out(reg) ret, options(nostack, preserves_flags));
        print_string("memset non-canonical dst: ");
        print_hex(addr);
        print_string(" len: ");
        print_hex(n as u64);
        print_string(" ret: ");
        print_hex(ret);
        print_string("\r\n");
        halt();
    }
    core::arch::asm!(
        "cld",
        "rep stosb",
        inout("rdi") dst => _,
        in("al") value as u8,
        inout("rcx") n => _,
        options(nostack, preserves_flags)
    );
    dst
}

fn fb_print_char(c: u8) {
    unsafe {
        let cols = (FB_INFO.width as usize) / 8;
        let rows = (FB_INFO.height as usize) / 16;

        match c {
            b'\r' => {
                CURSOR_X = 0;
                return;
            }
            b'\n' => {
                CURSOR_X = 0;
                CURSOR_Y += 1;
            }
            _ => {
                fb_draw_char(CURSOR_X * 8, CURSOR_Y * 16, c, 255, 255, 255);
                CURSOR_X += 1;
            }
        }

        if CURSOR_X >= cols {
            CURSOR_X = 0;
            CURSOR_Y += 1;
        }
        if CURSOR_Y >= rows {
            fb_clear(0, 0, 0);
            CURSOR_X = 0;
            CURSOR_Y = 0;
        }
    }
}

fn fb_clear(r: u8, g: u8, b: u8) {
    unsafe {
        let width = FB_INFO.width as usize;
        let height = FB_INFO.height as usize;
        for y in 0..height {
            for x in 0..width {
                fb_put_pixel(x, y, r, g, b);
            }
        }
    }
}

fn fb_put_pixel(x: usize, y: usize, r: u8, g: u8, b: u8) {
    unsafe {
        let pitch = (FB_INFO.pitch as usize) / 4;
        let fb_ptr = FB_INFO.address.as_u64() as *mut u32;
        let idx = y * pitch + x;

        let value = match FB_INFO.format {
            PixelFormat::Rgb => (r as u32) | ((g as u32) << 8) | ((b as u32) << 16),
            PixelFormat::Bgr => (b as u32) | ((g as u32) << 8) | ((r as u32) << 16),
        };

        core::ptr::write_volatile(fb_ptr.add(idx), value);
    }
}

fn fb_draw_char(x: usize, y: usize, c: u8, r: u8, g: u8, b: u8) {
    let idx = if c < 0x20 || c > 0x7f { b'?' } else { c };
    let glyph = FONT8X16_BASIC[idx as usize];

    for (row, bits) in glyph.iter().enumerate() {
        for col in 0..8 {
            let set = (bits >> (7 - col)) & 1 != 0;
            if set {
                fb_put_pixel(x + col, y + row, r, g, b);
            }
        }
    }
}

